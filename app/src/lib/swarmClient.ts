/**
 * STRATUM V3.0 — Swarm CLIENT: scheduled-universe search layer.
 *
 * ARCHITECTURE PIVOT (replaces the old trigger+poll model):
 *   On-demand hunt triggering is impossible on static GitHub Pages — there
 *   is no PAT in the browser, and git-push latency decouples the runner's
 *   disk from the polled raw.githubusercontent URL. So the swarm now runs
 *   on a 15-minute cron (.github/workflows/deploy-swarm.yml -> `scan-slate`)
 *   and commits ONE aggregate file: data/market_universe.json.
 *
 *   This module loads that file ONCE, caches it in module scope, and exposes
 *   pure client-side matching helpers. Typing = instant; ZERO network
 *   round-trips per hunt. There is deliberately NO startHunt() POST here —
 *   nothing in this file may issue a browser->workflow write.
 *
 * Backend contract (validated by schemas/market_universe.schema.json —
 * generated by scripts/swarm_runner.py scan-slate; DO NOT change shape):
 *   { generated_at_utc, next_refresh_estimate_utc, sources_status,
 *     fixture_count, fixtures: [ {fixture_id, home, away, sport, league,
 *     kickoff_utc, markets_scanned, top_edges[], agent_trace_lines[]} ] }
 */

/* ------------------------------------------------------------------ types */

export type SwarmAgent = 'SCOUT' | 'ACTUARY' | 'CONTEXT' | 'STRATEGIST';

/** Console/trace line as consumed by HunterConsole. SWARM = orchestrator. */
export interface HuntLine {
  agent: SwarmAgent | 'SWARM';
  text: string;
  ts: number; // seconds-into-cycle (backend logs relative time)
}

export type SourceStatus =
  | `ok(${number})`
  | 'blocked_by_waf'
  | 'timeout_on_load'
  | 'no_fixture_in_board'
  | 'deferred'
  | 'error'
  | (string & {});

/** One edge row — mirrors schemas/hunt_result.schema.json #/definitions/topEdge */
export interface TopEdge {
  market: string;
  selection: string;
  book_odds: number;
  fair_odds: number | null;
  ev_percent: number;
  confidence_score: number;
  kelly_stake_pct: number;
  reasoning_summary: string;
  best_bookmaker?: string;
  signals?: string[];
}

export interface UniverseFixture {
  fixture_id: string;
  home: string;
  away: string;
  sport: 'soccer' | 'nba' | 'nfl' | 'mlb' | 'nhl' | string;
  league: string;
  kickoff_utc: string;
  markets_scanned: number;
  top_edges: TopEdge[];
  agent_trace_lines: HuntLine[];
}

export interface MarketUniverse {
  schema_version?: string;
  generated_at_utc: string;
  next_refresh_estimate_utc: string;
  sources_status: Record<string, SourceStatus>;
  fixture_count: number;
  fixtures: UniverseFixture[];
  data_policy?: string;
  scan_stats?: Record<string, number>;
}

/** Legacy hunt report shape (still produced by single-hunt CLI/dev-server). */
export interface HuntResult {
  schema_version?: string;
  query: string;
  sport?: string;
  timestamp_utc: string;
  agents_executed: string[];
  agents_failed?: string[];
  markets_scanned_count: number;
  raw_prices_seen?: number;
  sources?: Record<string, string>;
  context_available?: boolean;
  mode?: string;
  top_edges: TopEdge[];
  visual_reports_png: string[];
  data_policy?: string;
  status: string;
  error_message?: string;
}

/** Replayable last-cycle console snapshot written by scan-slate. */
export interface HuntSnapshot {
  version?: string;
  query: string;
  sport: string;
  status: 'idle' | 'running' | 'complete' | 'no_results' | 'error';
  stage: string;
  progress: number;
  updated_at?: string;
  mode?: string;
  lines: HuntLine[];
  result: HuntResult | null;
  message?: string;
}

export class NetworkError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'NetworkError';
    Object.setPrototypeOf(this, NetworkError.prototype);
  }
}

